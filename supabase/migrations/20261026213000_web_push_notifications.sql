-- Web Push notification infrastructure for the student platform.
-- VAPID private key and webhook secret are stored separately in Supabase Vault;
-- never commit those secret values to source control.

create extension if not exists pg_net with schema extensions;

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  expiration_time bigint,
  user_agent text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint push_subscriptions_student_endpoint_key unique (student_id, endpoint)
);

create index if not exists push_subscriptions_student_id_idx
  on public.push_subscriptions(student_id);

alter table public.push_subscriptions enable row level security;

drop policy if exists "Students manage own push subscriptions" on public.push_subscriptions;
create policy "Students manage own push subscriptions"
  on public.push_subscriptions
  for all
  to authenticated
  using (student_id = public.current_student_id())
  with check (student_id = public.current_student_id());

grant select, insert, update, delete on public.push_subscriptions to authenticated;
grant usage, select on sequence public.push_subscriptions_id_seq to authenticated;

create or replace function public.get_web_push_config()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_object_agg(name, decrypted_secret), '{}'::jsonb)
  from vault.decrypted_secrets
  where name in ('web_push_vapid_public_key', 'web_push_vapid_private_key', 'web_push_vapid_subject', 'push_hook_secret');
$$;

revoke all on function public.get_web_push_config() from public, anon, authenticated;
grant execute on function public.get_web_push_config() to service_role;

create or replace function public.dispatch_notification_web_push()
returns trigger
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare
  hook_secret text;
begin
  select decrypted_secret into hook_secret
  from vault.decrypted_secrets
  where name = 'push_hook_secret'
  limit 1;

  if hook_secret is null or hook_secret = '' then
    raise warning 'Web Push hook secret is not configured; skipping push for notification %', NEW.id;
    return NEW;
  end if;

  perform net.http_post(
    url := 'https://nhdowqzecpwmkunczodl.supabase.co/functions/v1/send-web-push',
    body := jsonb_build_object('record', to_jsonb(NEW)),
    params := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-push-hook-secret', hook_secret
    ),
    timeout_milliseconds := 5000
  );

  return NEW;
end;
$$;

revoke all on function public.dispatch_notification_web_push() from public, anon, authenticated;

drop trigger if exists dispatch_notification_web_push_after_insert on public.notifications;
create trigger dispatch_notification_web_push_after_insert
after insert on public.notifications
for each row
execute function public.dispatch_notification_web_push();
